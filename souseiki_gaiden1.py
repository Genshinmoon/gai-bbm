def paragraphs(text):
    """章の本文を段落(行のリスト)のリストにする。"""
    return [p.split("\n") for p in text.strip().split("\n\n")]


def to_dict():
    return {
        "series": SERIES,
        "title": TITLE,
        "chapters": [{"title": t, "paragraphs": paragraphs(x)} for t, x in CHAPTERS],
    }


def typeout(text, delay):
    for ch in text:
        sys.stdout.write(ch)
        sys.stdout.flush()
        if delay:
            time.sleep(delay * (6 if ch in "。、！？…" else 1))
    sys.stdout.write("\n")


def show_paragraph(lines, delay):
    for line in lines:
        if line.startswith("《"):
            sys.stdout.write(CYAN)
            typeout("> " + line, delay / 2)
            sys.stdout.write(RST)
        else:
            typeout(line, delay)
    time.sleep(0.5 if delay else 0)
    print()


def main():
    ap = argparse.ArgumentParser(description=TITLE)
    ap.add_argument("-c", "--chapter", type=int, default=0, help="開始章 (0=序, 1, 2)")
    ap.add_argument("-f", "--fast", action="store_true", help="文字送りなし")
    ap.add_argument("-l", "--list", action="store_true", help="目次")
    ap.add_argument("-j", "--json", action="store_true", help="JSON出力")
    a = ap.parse_args()

    if a.list:
        for i, (t, _) in enumerate(CHAPTERS):
            print(f"{i}. {t}")
        return
    if a.json:
        json.dump(to_dict(), sys.stdout, ensure_ascii=False, indent=2)
        print()
        return

    delay = 0 if a.fast else 0.04
    print(f"\n{GOLD}☀️🌕 {SERIES}\n{TITLE}{RST}\n")
    try:
        for t, x in CHAPTERS[a.chapter:]:
            print(f"{DIM}-- {t} --{RST}\n")
            for p in paragraphs(x):
                show_paragraph(p, delay)
            input(f"{DIM}[Enter で次へ]{RST}")
            print()
    except (KeyboardInterrupt, EOFError):
        print("\n")
        return
    print(f"{GOLD}【記録 完】{RST}")


if __name__ == "__main__":
    main()
